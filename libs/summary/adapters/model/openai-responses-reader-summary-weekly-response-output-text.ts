import { isOpenAiGeneratedTextContent } from "./openai-responses-completion-state";
import { modelError } from "./openai-responses-reader-summary-weekly-response-failure";
import { asRecord, nonEmptyString } from "./openai-responses-reader-summary-weekly-response-records";

export const extractSingleOutputText = (
  response: Record<string, unknown>,
): string => {
  const aggregate = nonEmptyString(response.output_text);
  const fragments: string[] = [];
  if (response.output !== undefined && !Array.isArray(response.output)) {
    throw modelError(
      "invalid_response",
      false,
      "OpenAI reader summary weekly output must be an array",
    );
  }
  for (const item of Array.isArray(response.output) ? response.output : []) {
    const output = asRecord(item);
    if (output === null || output.content === undefined) {
      continue;
    }
    if (!Array.isArray(output.content)) {
      throw modelError(
        "invalid_response",
        false,
        "OpenAI reader summary weekly output content must be an array",
      );
    }
    for (const itemContent of output.content) {
      const content = asRecord(itemContent);
      if (
        content === null ||
        (content.text !== undefined && typeof content.text !== "string")
      ) {
        throw modelError(
          "invalid_response",
          false,
          "OpenAI reader summary weekly output content is invalid",
        );
      }
      if (output.type === "reasoning" && content.type === "reasoning_text") {
        if (typeof content.text !== "string") {
          throw modelError(
            "invalid_response",
            false,
            "OpenAI reader summary weekly reasoning content is invalid",
          );
        }
        continue;
      }
      const text = nonEmptyString(content.text);
      if (text !== undefined && !isOpenAiGeneratedTextContent(output, content, false)) {
        throw modelError(
          "invalid_response",
          false,
          "OpenAI reader summary weekly output text must be generated by the assistant",
        );
      }
      if (content.type !== "output_text") {
        continue;
      }
      if (text === undefined) {
        throw modelError(
          "invalid_response",
          false,
          "OpenAI reader summary weekly output text is empty",
        );
      }
      fragments.push(text);
    }
  }
  if (fragments.length > 1) {
    throw modelError(
      "invalid_response",
      false,
      "OpenAI reader summary weekly response contains stitched output text",
    );
  }
  if (
    aggregate !== undefined &&
    fragments.length === 1 &&
    aggregate !== fragments[0]
  ) {
    throw modelError(
      "invalid_response",
      false,
      "OpenAI reader summary weekly aggregate output text is inconsistent",
    );
  }
  const outputText = aggregate ?? fragments[0];
  if (outputText === undefined) {
    throw modelError(
      "invalid_response",
      false,
      "OpenAI reader summary weekly response has no output text",
    );
  }
  return outputText;
};
